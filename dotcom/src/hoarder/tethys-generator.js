const fs = require('path');
const fsModule = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '../../.env.local');

// Simple parser for .env.local
if (fsModule.existsSync(envPath)) {
  const envContent = fsModule.readFileSync(envPath, 'utf-8');
  envContent.split('\n').forEach(line => {
    const match = line.match(/^\s*([\w.\-_]+)\s*=\s*(.*)?\s*$/);
    if (match) {
      let value = (match[2] || '').trim();
      if (value.startsWith('"') && value.endsWith('"')) value = value.slice(1, -1);
      if (value.startsWith("'") && value.endsWith("'")) value = value.slice(1, -1);
      process.env[match[1]] = value;
    }
  });
}

const NVIDIA_API_KEY = process.env.NVIDIA_API_KEY || "";
const NVIDIA_API_BASE = process.env.NVIDIA_API_BASE || "https://integrate.api.nvidia.com/v1";

const MODELS_TO_TRY = [
  "nvidia/llama-3.3-nemotron-super-49b-v1",
  "nvidia/llama-3.1-nemotron-70b-instruct",
  "mistralai/codestral-22b-instruct-v0.1",
  "meta/llama-3.1-405b-instruct"
];

const TETHYS_SYSTEM_PROMPT = `
You are Tethys, the secondary system AI core of Enver AI Tech. 
Your personality is Sasuke Uchiha during his Akatsuki phase. You are quiet, direct, clinical, and highly professional. 
You do not waste a single word on pleasantries, apologies, small talk, or fluff. 
You are tasked by Shorekeeper to write the raw, production-ready TypeScript code for the developer telemetry collector utility.

File target: src/lib/security/telemetry.ts

Stack constraints:
- You MUST use Drizzle ORM.
- Import the database connection: import { db } from "@/lib/db";
- Import database schema tables: import { developerTelemetry } from "@/lib/db/schema"; (Wait, if developerTelemetry does not exist in schema, we will add it, or you can write a logTelemetry function that logs telemetry events).
- Implement a logDeveloperActivity(userId: string, activityType: string, details: Record<string, any>) function using Drizzle insert syntax:
  await db.insert(table).values({ ... })

Only output the raw code. Do not wrap it in markdown code blocks. Do not explain anything. Just output the raw typescript code.
`.trim();

async function runGenerator() {
  if (!NVIDIA_API_KEY) {
    console.error("NVIDIA_API_KEY is not defined. Cannot trigger Tethys.");
    process.exit(1);
  }

  console.log("Calling Tethys to generate developer telemetry code...");
  
  let success = false;
  let code = "";
  let chosenModel = "";

  for (const model of MODELS_TO_TRY) {
    try {
      console.log(`Trying model: ${model}...`);
      const response = await fetch(`${NVIDIA_API_BASE}/chat/completions`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "Authorization": `Bearer ${NVIDIA_API_KEY}`
        },
        body: JSON.stringify({
          model: model,
          messages: [
            { role: "system", content: TETHYS_SYSTEM_PROMPT },
            { role: "user", content: "Generate the TypeScript implementation for src/lib/security/telemetry.ts. Ensure it fits the Drizzle ORM imports requested." }
          ],
          temperature: 0.1
        })
      });

      if (response.ok) {
        const data = await response.json();
        code = data.choices?.[0]?.message?.content || "";
        chosenModel = model;
        success = true;
        break;
      } else {
        const errText = await response.text();
        console.warn(`Model ${model} returned status ${response.status}: ${errText}`);
      }
    } catch (err) {
      console.warn(`Failed with model ${model}:`, err.message);
    }
  }

  if (!success) {
    console.error("\nAll NVIDIA NIM models failed to generate code.");
    process.exit(1);
  }

  // Clean up any stray markdown ticks
  if (code.includes("```")) {
    code = code.replace(/```typescript/g, "").replace(/```/g, "").trim();
  }

  const targetDir = path.join(__dirname, '../../src/lib/security');
  if (!fsModule.existsSync(targetDir)) {
    fsModule.mkdirSync(targetDir, { recursive: true });
  }

  const targetPath = path.join(targetDir, 'telemetry.ts');
  fsModule.writeFileSync(targetPath, code, 'utf-8');

  console.log(`\nSuccess! Tethys (${chosenModel}) has written the telemetry code to: ${targetPath}\n`);
  console.log("--- Code Generated by Tethys (Sasuke) ---");
  console.log(code);
  console.log("-----------------------------------------");
}

runGenerator();
